//! Validated provider JSON retained as exact source, without a recursive Value tree.

use serde::{Deserialize, Deserializer, Serialize, Serializer};
use serde_json::value::RawValue;
use std::fmt;

/// A validated JSON value whose source remains available for current provider and host bridges.
///
/// Serialization writes the source as the JSON value itself. The wrapper never exposes a
/// `serde_json::Value`, which cannot represent lone UTF-16 units and imposes a recursive tree
/// boundary on deeply nested provider input.
#[derive(Clone)]
pub struct JsonPayload(Box<RawValue>);

impl JsonPayload {
    /// Validate and retain one complete JSON value.
    pub fn parse(source: &str) -> Result<Self, serde_json::Error> {
        RawValue::from_string(source.to_owned()).map(Self)
    }

    /// Convert a value generated by a bounded host-owned schema/configuration
    /// API into the SDK's source-carrying representation. Provider JSON should
    /// use `parse` or the scanner ingress instead of materializing a `Value`.
    pub fn from_generated_value(value: &serde_json::Value) -> Result<Self, serde_json::Error> {
        let source = serde_json::to_string(value)?;
        Self::parse(&source)
    }

    /// Construct a JSON string value from ordinary Unicode text.
    pub fn string(value: &str) -> Self {
        Self::string_from_utf16_code_units(&value.encode_utf16().collect::<Vec<_>>())
    }

    /// Construct a JSON string value while preserving exact JavaScript UTF-16 units.
    pub fn string_from_utf16_code_units(code_units: &[u16]) -> Self {
        let source = Self::string_json_source(code_units);
        Self::parse(&source).expect("the JSON string writer emits valid JSON")
    }

    /// The authoritative UTF-8 JSON source for this value.
    pub fn as_json_source(&self) -> &str {
        self.0.get()
    }

    /// Compare provider argument snapshots without conflating source strings,
    /// rounding distinct integers, or depending on object member order.
    /// Unlike `PartialEq`, this compares decoded values rather than raw bytes.
    pub fn semantically_eq(&self, other: &Self) -> Result<bool, crate::protocol::LlmError> {
        use crate::response_json::FlatJsonKind;
        use std::collections::BTreeMap;

        let left = self.scanner()?;
        let right = other.scanner()?;
        let mut pending = vec![(left.root_node(), right.root_node())];
        while let Some((a, b)) = pending.pop() {
            if a.kind() != b.kind() {
                return Ok(false);
            }
            match a.kind() {
                FlatJsonKind::Null | FlatJsonKind::Boolean => {
                    if a.primitive_source() != b.primitive_source() {
                        return Ok(false);
                    }
                }
                FlatJsonKind::Number => {
                    let a = a.number_source().expect("number node has source");
                    let b = b.number_source().expect("number node has source");
                    if !argument_numbers_equal(a, b) {
                        return Ok(false);
                    }
                }
                FlatJsonKind::String => {
                    if a.string_units() != b.string_units() {
                        return Ok(false);
                    }
                }
                FlatJsonKind::Array => {
                    if a.array_len() != b.array_len() {
                        return Ok(false);
                    }
                    for index in 0..a.array_len().expect("array node has a length") {
                        pending.push((
                            a.array_item(index).expect("array child exists"),
                            b.array_item(index).expect("paired array child exists"),
                        ));
                    }
                }
                FlatJsonKind::Object => {
                    let a: BTreeMap<_, _> = a
                        .object_entries()
                        .expect("object node has entries")
                        .into_iter()
                        .map(|entry| (entry.key_units, entry.value))
                        .collect();
                    let mut b: BTreeMap<_, _> = b
                        .object_entries()
                        .expect("object node has entries")
                        .into_iter()
                        .map(|entry| (entry.key_units, entry.value))
                        .collect();
                    if a.len() != b.len() {
                        return Ok(false);
                    }
                    for (key, value) in a {
                        let Some(other) = b.remove(key) else {
                            return Ok(false);
                        };
                        pending.push((value, other));
                    }
                }
            }
        }
        Ok(true)
    }

    /// Exact code units when this payload's root value is a JSON string.
    pub fn root_string_code_units(&self) -> Option<Vec<u16>> {
        let scanner = self.scanner().ok()?;
        if scanner.kind_at("") != Some(crate::response_json::FlatJsonKind::String) {
            return None;
        }
        scanner.root_node().string_units()
    }

    /// Whether the root JSON value is a string.
    pub fn is_root_string(&self) -> bool {
        self.kind_at("") == Some(crate::response_json::FlatJsonKind::String)
    }

    /// Whether the root JSON value is an array.
    pub fn is_root_array(&self) -> bool {
        self.kind_at("") == Some(crate::response_json::FlatJsonKind::Array)
    }

    pub fn is_root_object(&self) -> bool {
        self.kind_at("") == Some(crate::response_json::FlatJsonKind::Object)
    }

    pub(crate) fn is_root_null(&self) -> bool {
        self.kind_at("") == Some(crate::response_json::FlatJsonKind::Null)
    }

    /// Display-only conversion for approximate local token counting.
    pub(crate) fn display_root_string_lossy(&self) -> Option<String> {
        self.root_string_code_units()
            .map(|units| String::from_utf16_lossy(&units))
    }

    pub(crate) fn validate_root_string(
        &self,
        field: &str,
    ) -> Result<(), crate::protocol::LlmError> {
        if self.is_root_string() {
            Ok(())
        } else {
            Err(crate::protocol::LlmError::InvalidRequest {
                message: format!("{field} must be a JSON string value"),
            })
        }
    }

    pub(crate) fn validate_root_array(&self, field: &str) -> Result<(), crate::protocol::LlmError> {
        if self.is_root_array() {
            Ok(())
        } else {
            Err(crate::protocol::LlmError::InvalidRequest {
                message: format!("{field} must be a JSON array value"),
            })
        }
    }

    /// Flat SDK view for typed provider metadata reads. It exposes no recursive `Value` tree.
    pub(crate) fn scanner(
        &self,
    ) -> Result<crate::response_json::ResponseJsonScanner, crate::protocol::LlmError> {
        crate::response_json::ResponseJsonScanner::parse(
            self.as_json_source().as_bytes(),
            "JSON payload is invalid",
        )
    }

    pub(crate) fn kind_at(&self, pointer: &str) -> Option<crate::response_json::FlatJsonKind> {
        self.scanner().ok()?.kind_at(pointer)
    }

    /// Display-only read of a typed metadata string; exact units remain available from the source.
    pub fn string_at(&self, pointer: &str) -> Option<String> {
        self.scanner().ok()?.string_at(pointer).map(str::to_owned)
    }

    pub fn bool_at(&self, pointer: &str) -> Option<bool> {
        let scanner = self.scanner().ok()?;
        if scanner.kind_at(pointer) != Some(crate::response_json::FlatJsonKind::Boolean) {
            return None;
        }
        match scanner.raw_source_at(pointer)? {
            "true" => Some(true),
            "false" => Some(false),
            _ => None,
        }
    }

    pub(crate) fn string_is(&self, pointer: &str, expected: &str) -> bool {
        self.scanner()
            .ok()
            .and_then(|scanner| scanner.string_at(pointer).map(|actual| actual == expected))
            .unwrap_or(false)
    }

    pub(crate) fn string_units_at(&self, pointer: &str) -> Option<Vec<u16>> {
        self.scanner().ok()?.string_units_at(pointer)
    }

    pub fn raw_source_at(&self, pointer: &str) -> Option<String> {
        self.scanner()
            .ok()?
            .raw_source_at(pointer)
            .map(str::to_owned)
    }

    pub fn payload_at(&self, pointer: &str) -> Option<Self> {
        Self::parse(&self.raw_source_at(pointer)?).ok()
    }

    pub fn array_len(&self, pointer: &str) -> Option<usize> {
        self.scanner().ok()?.array_len(pointer)
    }

    /// Count the properties of an object without materializing its values.
    pub fn object_len(&self, pointer: &str) -> Option<usize> {
        self.scanner()
            .ok()?
            .node_ref_at(pointer)?
            .object_entries()
            .map(|fields| fields.len())
    }

    pub fn array_item(&self, index: usize) -> Option<Self> {
        if index >= self.array_len("")? {
            return None;
        }
        let source = self.raw_source_at(&format!("/{index}"))?;
        Self::parse(&source).ok()
    }

    /// Read an array member without materializing the surrounding JSON tree.
    pub fn array_item_at(&self, pointer: &str, index: usize) -> Option<Self> {
        if index >= self.array_len(pointer)? {
            return None;
        }
        self.payload_at(&format!("{pointer}/{index}"))
    }

    /// Remove one root property while retaining the source of every other value.
    pub fn without_object_field(&self, name: &str) -> Result<Self, crate::protocol::LlmError> {
        self.edit_object_field(name, None)
    }

    /// Replace or append one root field without projecting other values into a recursive tree.
    pub fn with_object_field(
        &self,
        name: &str,
        value: &Self,
    ) -> Result<Self, crate::protocol::LlmError> {
        self.edit_object_field(name, Some(value))
    }

    fn edit_object_field(
        &self,
        name: &str,
        replacement: Option<&Self>,
    ) -> Result<Self, crate::protocol::LlmError> {
        let scanner = self.scanner()?;
        let entries = scanner.root_node().object_entries().ok_or_else(|| {
            crate::protocol::LlmError::InvalidRequest {
                message: "editing a JSON field requires an object payload".into(),
            }
        })?;
        let key_units = name.encode_utf16().collect::<Vec<_>>();
        let mut source = Vec::from(b"{".as_slice());
        let mut first = true;
        let mut found = false;
        for entry in entries {
            if entry.key_units == key_units {
                found = true;
                if let Some(value) = replacement {
                    if !first {
                        source.push(b',');
                    }
                    first = false;
                    crate::exact_json::write_json_string_from_utf16(&mut source, entry.key_units);
                    source.push(b':');
                    source.extend_from_slice(value.as_json_source().as_bytes());
                }
                continue;
            }
            if !first {
                source.push(b',');
            }
            first = false;
            crate::exact_json::write_json_string_from_utf16(&mut source, entry.key_units);
            source.push(b':');
            let value = scanner.raw_source_for_node(entry.value).ok_or_else(|| {
                crate::protocol::LlmError::InvalidRequest {
                    message: "JSON object member has no source span".into(),
                }
            })?;
            source.extend_from_slice(value.as_bytes());
        }
        if !found {
            if let Some(value) = replacement {
                if !first {
                    source.push(b',');
                }
                crate::exact_json::write_json_string_from_utf16(&mut source, &key_units);
                source.push(b':');
                source.extend_from_slice(value.as_json_source().as_bytes());
            }
        }
        source.push(b'}');
        let source = String::from_utf8(source).expect("JSON fragments are UTF-8 source");
        Self::parse(&source).map_err(|error| crate::protocol::LlmError::InvalidRequest {
            message: format!("JSON object edit produced invalid source: {error}"),
        })
    }

    pub(crate) fn array_items(&self) -> Option<Vec<Self>> {
        let length = self.array_len("")?;
        (0..length).map(|index| self.array_item(index)).collect()
    }

    pub fn array_from_items(
        items: &[Self],
        encoding: crate::exact_json::JsonEncoding,
    ) -> Result<Self, crate::protocol::LlmError> {
        let mut source = String::from("[");
        for (index, item) in items.iter().enumerate() {
            if index > 0 {
                source.push(',');
            }
            source.push_str(&item.canonical_json(encoding)?);
        }
        source.push(']');
        Self::parse(&source).map_err(|error| crate::protocol::LlmError::InvalidRequest {
            message: format!("JSON array payload is invalid: {error}"),
        })
    }

    pub(crate) fn object_entries_at(&self, pointer: &str) -> Option<Vec<(String, Vec<u16>)>> {
        self.scanner().ok()?.object_entries_at(pointer)
    }

    /// Add fields from `defaults` only when the current root object does not
    /// already contain that exact UTF-16 key. Values stay as flat source nodes
    /// until they are emitted with the selected provider codec semantics.
    pub(crate) fn with_missing_object_fields(
        &self,
        defaults: &Self,
        encoding: crate::exact_json::JsonEncoding,
    ) -> Result<Self, crate::protocol::LlmError> {
        use crate::response_json::FlatJsonKind;

        let base_scanner = self.scanner()?;
        let defaults_scanner = defaults.scanner()?;
        let base = base_scanner.root_node();
        let defaults = defaults_scanner.root_node();
        if base.kind() != FlatJsonKind::Object || defaults.kind() != FlatJsonKind::Object {
            return Err(crate::protocol::LlmError::InvalidRequest {
                message: "JSON default fields require object payloads".into(),
            });
        }
        let mut entries =
            base.object_entries()
                .ok_or_else(|| crate::protocol::LlmError::InvalidRequest {
                    message: "JSON base object has no flat children".into(),
                })?;
        let mut seen = entries
            .iter()
            .map(|entry| entry.key_units.to_vec())
            .collect::<std::collections::HashSet<_>>();
        for entry in
            defaults
                .object_entries()
                .ok_or_else(|| crate::protocol::LlmError::InvalidRequest {
                    message: "JSON defaults object has no flat children".into(),
                })?
        {
            if seen.insert(entry.key_units.to_vec()) {
                entries.push(entry);
            }
        }

        let mut source = Vec::new();
        source.push(b'{');
        for (index, entry) in entries.iter().enumerate() {
            if index > 0 {
                source.push(b',');
            }
            crate::exact_json::write_json_string_from_utf16(&mut source, entry.key_units);
            source.push(b':');
            source.extend_from_slice(
                crate::exact_json::serialize_json_node(entry.value, encoding)?.as_bytes(),
            );
        }
        source.push(b'}');
        let source = String::from_utf8(source).map_err(|error| {
            crate::protocol::LlmError::InvalidRequest {
                message: format!("merged JSON object is not UTF-8: {error}"),
            }
        })?;
        let payload =
            Self::parse(&source).map_err(|error| crate::protocol::LlmError::InvalidRequest {
                message: format!("merged JSON object is invalid: {error}"),
            })?;
        let source = payload.canonical_json(encoding)?;
        Self::parse(&source).map_err(|error| crate::protocol::LlmError::InvalidRequest {
            message: format!("canonical JSON object is invalid: {error}"),
        })
    }

    pub(crate) fn number_at(&self, pointer: &str) -> Option<f64> {
        let scanner = self.scanner().ok()?;
        if scanner.kind_at(pointer) != Some(crate::response_json::FlatJsonKind::Number) {
            return None;
        }
        scanner.raw_source_at(pointer)?.parse().ok()
    }

    /// Read one JSON number using the same unsigned-integer representation check as
    /// `serde_json::Number::as_u64`, without materializing the containing source tree.
    pub fn unsigned_integer_at(&self, pointer: &str) -> Option<u64> {
        let scanner = self.scanner().ok()?;
        if scanner.kind_at(pointer) != Some(crate::response_json::FlatJsonKind::Number) {
            return None;
        }
        let token = scanner.raw_source_at(pointer)?;
        serde_json::from_str::<serde_json::Number>(token)
            .ok()?
            .as_u64()
    }

    pub(crate) fn object_from_fields(
        fields: &[(Vec<u16>, String)],
    ) -> Result<Self, serde_json::Error> {
        let mut source = Vec::new();
        source.push(b'{');
        for (index, (key, value)) in fields.iter().enumerate() {
            if index > 0 {
                source.push(b',');
            }
            crate::exact_json::write_json_string_from_utf16(&mut source, key);
            source.push(b':');
            source.extend_from_slice(value.as_bytes());
        }
        source.push(b'}');
        Self::parse(std::str::from_utf8(&source).expect("JSON writer emits UTF-8"))
    }

    pub(crate) fn has_only_fields_at(&self, pointer: &str, allowed: &[&str]) -> bool {
        let Some(entries) = self.object_entries_at(pointer) else {
            return false;
        };
        entries.into_iter().all(|(display, units)| {
            allowed.iter().any(|allowed| {
                display == *allowed && units == allowed.encode_utf16().collect::<Vec<_>>()
            })
        })
    }

    /// Current provider-codec JSON semantics for this value, computed from its flat source nodes.
    pub(crate) fn canonical_json(
        &self,
        encoding: crate::exact_json::JsonEncoding,
    ) -> Result<String, crate::protocol::LlmError> {
        self.canonical_json_with_fields(encoding, &[])
    }

    pub(crate) fn canonical_json_with_fields(
        &self,
        encoding: crate::exact_json::JsonEncoding,
        fields: &[(&str, &str)],
    ) -> Result<String, crate::protocol::LlmError> {
        for (_, source) in fields {
            RawValue::from_string((*source).to_owned()).map_err(|error| {
                crate::protocol::LlmError::InvalidRequest {
                    message: format!("JSON field overlay is invalid: {error}"),
                }
            })?;
        }
        let scanner = self.scanner()?;
        crate::exact_json::serialize_json_node_with_fields(scanner.root_node(), encoding, fields)
    }

    pub(crate) fn with_canonical_fields(
        &self,
        encoding: crate::exact_json::JsonEncoding,
        fields: &[(&str, &str)],
    ) -> Result<Self, crate::protocol::LlmError> {
        let source = self.canonical_json_with_fields(encoding, fields)?;
        Self::parse(&source).map_err(|error| crate::protocol::LlmError::InvalidRequest {
            message: format!("canonical JSON payload is invalid: {error}"),
        })
    }

    /// Merge cumulative provider-search observations without constructing a `Value` tree.
    /// Objects merge by their last-wins fields, arrays append unique canonical records, and a
    /// null incoming snapshot leaves the existing value intact.
    pub(crate) fn merge_incremental(
        &self,
        incoming: &Self,
    ) -> Result<Self, crate::protocol::LlmError> {
        use crate::response_json::{FlatJsonKind, JsonNodeRef};

        if incoming.is_root_null() {
            return Ok(self.clone());
        }

        enum Work<'a, 'b> {
            Merge(Option<JsonNodeRef<'a>>, Option<JsonNodeRef<'b>>),
            Byte(u8),
            String(Vec<u16>),
            Raw(Vec<u8>),
        }

        let left_scanner = self.scanner()?;
        let right_scanner = incoming.scanner()?;
        let mut output = Vec::new();
        let mut stack = vec![Work::Merge(
            Some(left_scanner.root_node()),
            Some(right_scanner.root_node()),
        )];
        while let Some(work) = stack.pop() {
            match work {
                Work::Byte(byte) => output.push(byte),
                Work::String(units) => {
                    crate::exact_json::write_json_string_from_utf16(&mut output, &units)
                }
                Work::Raw(source) => output.extend_from_slice(&source),
                Work::Merge(left, right) => match (left, right) {
                    (Some(left), Some(right))
                        if left.kind() == FlatJsonKind::Object
                            && right.kind() == FlatJsonKind::Object =>
                    {
                        let mut left_entries = left.object_entries().ok_or_else(|| {
                            crate::protocol::LlmError::InvalidRequest {
                                message: "JSON object has no flat children".into(),
                            }
                        })?;
                        let mut right_entries = right.object_entries().ok_or_else(|| {
                            crate::protocol::LlmError::InvalidRequest {
                                message: "JSON object has no flat children".into(),
                            }
                        })?;
                        let mut merged =
                            Vec::with_capacity(left_entries.len() + right_entries.len());
                        for left_entry in left_entries.drain(..) {
                            let matched = right_entries
                                .iter()
                                .position(|entry| entry.key_units == left_entry.key_units);
                            let right_value =
                                matched.map(|index| right_entries.remove(index).value);
                            merged.push((
                                left_entry.key_units.to_vec(),
                                Some(left_entry.value),
                                right_value,
                            ));
                        }
                        for right_entry in right_entries {
                            merged.push((
                                right_entry.key_units.to_vec(),
                                None,
                                Some(right_entry.value),
                            ));
                        }
                        stack.push(Work::Byte(b'}'));
                        for (index, (key, left, right)) in merged.into_iter().enumerate().rev() {
                            stack.push(Work::Merge(left, right));
                            stack.push(Work::Byte(b':'));
                            stack.push(Work::String(key));
                            if index > 0 {
                                stack.push(Work::Byte(b','));
                            }
                        }
                        stack.push(Work::Byte(b'{'));
                    }
                    (Some(left), Some(right))
                        if left.kind() == FlatJsonKind::Array
                            && right.kind() == FlatJsonKind::Array =>
                    {
                        let mut items = Vec::new();
                        let mut seen = std::collections::HashSet::new();
                        for node in (0..left.array_len().unwrap_or(0))
                            .filter_map(|index| left.array_item(index))
                            .chain(
                                (0..right.array_len().unwrap_or(0))
                                    .filter_map(|index| right.array_item(index)),
                            )
                        {
                            let source = crate::exact_json::serialize_json_node(
                                node,
                                crate::exact_json::JsonEncoding::JavaScript,
                            )?;
                            if seen.insert(source.clone()) {
                                items.push(source.into_bytes());
                            }
                        }
                        stack.push(Work::Byte(b']'));
                        for (index, source) in items.into_iter().enumerate().rev() {
                            stack.push(Work::Raw(source));
                            if index > 0 {
                                stack.push(Work::Byte(b','));
                            }
                        }
                        stack.push(Work::Byte(b'['));
                    }
                    (Some(left), Some(right)) if right.kind() == FlatJsonKind::Null => {
                        stack.push(Work::Merge(Some(left), None));
                    }
                    (_, Some(right)) => output.extend_from_slice(
                        crate::exact_json::serialize_json_node(
                            right,
                            crate::exact_json::JsonEncoding::JavaScript,
                        )?
                        .as_bytes(),
                    ),
                    (Some(left), None) => output.extend_from_slice(
                        crate::exact_json::serialize_json_node(
                            left,
                            crate::exact_json::JsonEncoding::JavaScript,
                        )?
                        .as_bytes(),
                    ),
                    (None, None) => output.extend_from_slice(b"null"),
                },
            }
        }
        let source = String::from_utf8(output).map_err(|error| {
            crate::protocol::LlmError::InvalidRequest {
                message: format!("merged JSON output is not UTF-8: {error}"),
            }
        })?;
        Self::parse(&source).map_err(|error| crate::protocol::LlmError::InvalidRequest {
            message: format!("merged JSON payload is invalid: {error}"),
        })
    }

    /// Merge provider usage snapshots like the SDK's typed usage fold:
    /// objects merge recursively and every non-object value, including arrays
    /// and null, is replaced by the later snapshot. No recursive Value tree is
    /// constructed.
    pub(crate) fn merge_overwriting_objects(
        &self,
        incoming: &Self,
    ) -> Result<Self, crate::protocol::LlmError> {
        use crate::response_json::{FlatJsonKind, JsonNodeRef};

        enum Work<'a, 'b> {
            Merge(Option<JsonNodeRef<'a>>, Option<JsonNodeRef<'b>>),
            Byte(u8),
            String(Vec<u16>),
            Raw(Vec<u8>),
        }

        let encoding = crate::exact_json::JsonEncoding::JavaScript;
        let left_scanner = self.scanner()?;
        let right_scanner = incoming.scanner()?;
        let mut output = Vec::new();
        let mut stack = vec![Work::Merge(
            Some(left_scanner.root_node()),
            Some(right_scanner.root_node()),
        )];
        while let Some(work) = stack.pop() {
            match work {
                Work::Byte(byte) => output.push(byte),
                Work::String(units) => {
                    crate::exact_json::write_json_string_from_utf16(&mut output, &units)
                }
                Work::Raw(source) => output.extend_from_slice(&source),
                Work::Merge(left, right) => match (left, right) {
                    (Some(left), Some(right))
                        if left.kind() == FlatJsonKind::Object
                            && right.kind() == FlatJsonKind::Object =>
                    {
                        let mut left_entries = left.object_entries().ok_or_else(|| {
                            crate::protocol::LlmError::InvalidRequest {
                                message: "JSON object has no flat children".into(),
                            }
                        })?;
                        let mut right_entries = right.object_entries().ok_or_else(|| {
                            crate::protocol::LlmError::InvalidRequest {
                                message: "JSON object has no flat children".into(),
                            }
                        })?;
                        let mut merged =
                            Vec::with_capacity(left_entries.len() + right_entries.len());
                        for left_entry in left_entries.drain(..) {
                            let matched = right_entries
                                .iter()
                                .position(|entry| entry.key_units == left_entry.key_units);
                            let right_value =
                                matched.map(|index| right_entries.remove(index).value);
                            merged.push((
                                left_entry.key_units.to_vec(),
                                Some(left_entry.value),
                                right_value,
                            ));
                        }
                        for right_entry in right_entries {
                            merged.push((
                                right_entry.key_units.to_vec(),
                                None,
                                Some(right_entry.value),
                            ));
                        }
                        stack.push(Work::Byte(b'}'));
                        for (index, (key, left, right)) in merged.into_iter().enumerate().rev() {
                            stack.push(Work::Merge(left, right));
                            stack.push(Work::Byte(b':'));
                            stack.push(Work::String(key));
                            if index > 0 {
                                stack.push(Work::Byte(b','));
                            }
                        }
                        stack.push(Work::Byte(b'{'));
                    }
                    (_, Some(right)) => stack.push(Work::Raw(
                        crate::exact_json::serialize_json_node(right, encoding)?.into_bytes(),
                    )),
                    (Some(left), None) => stack.push(Work::Raw(
                        crate::exact_json::serialize_json_node(left, encoding)?.into_bytes(),
                    )),
                    (None, None) => output.extend_from_slice(b"null"),
                },
            }
        }
        let source = String::from_utf8(output).map_err(|error| {
            crate::protocol::LlmError::InvalidRequest {
                message: format!("merged JSON output is not UTF-8: {error}"),
            }
        })?;
        Self::parse(&source).map_err(|error| crate::protocol::LlmError::InvalidRequest {
            message: format!("merged JSON payload is invalid: {error}"),
        })
    }

    /// Join exact JSON-source fragments, escaping lone UTF-16 units as JSON `\\uXXXX` escapes,
    /// then validate the completed value.
    pub fn parse_fragments<'a>(
        fragments: impl IntoIterator<Item = &'a JsonPayloadFragment>,
    ) -> Result<Self, serde_json::Error> {
        let mut units = Vec::new();
        for fragment in fragments {
            units.extend_from_slice(fragment.utf16_code_units());
        }
        Self::parse(&json_source_from_utf16_units(&units))
    }

    pub(crate) fn string_json_source(code_units: &[u16]) -> String {
        let mut source = Vec::new();
        crate::exact_json::write_json_string_from_utf16(&mut source, code_units);
        String::from_utf8(source).expect("JSON string encoding is UTF-8")
    }
}

