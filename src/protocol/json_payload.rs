/// One exact UTF-16 fragment of a provider's JSON argument source.
///
/// Stream frames carry fragments before they form a complete JSON value. A plain Rust `String`
/// cannot represent an unpaired JavaScript UTF-16 unit, so fragments always retain their exact
/// units and expose no lossy string fallback.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct JsonPayloadFragment(Vec<u16>);

impl JsonPayloadFragment {
    /// Capture a scalar UTF-8 source fragment as its exact UTF-16 units.
    pub fn from_text(source: &str) -> Self {
        Self(source.encode_utf16().collect())
    }

    /// Construct a fragment from exact JavaScript string units.
    pub fn from_utf16_code_units(code_units: Vec<u16>) -> Self {
        Self(code_units)
    }

    /// The exact source units carried by this fragment.
    pub fn utf16_code_units(&self) -> &[u16] {
        &self.0
    }

    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }

    /// Construct a fragment from a display string and its optional exact-unit sidecar.
    pub(crate) fn from_decoded_text(
        display: &str,
        utf16_code_units: Option<Vec<u16>>,
    ) -> Result<Self, &'static str> {
        match utf16_code_units {
            Some(code_units) if String::from_utf16_lossy(&code_units) == display => {
                Ok(Self(code_units))
            }
            Some(_) => Err("JSON source fragment units do not match their display string"),
            None => Ok(Self::from_text(display)),
        }
    }
}

impl Serialize for JsonPayloadFragment {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: Serializer,
    {
        let mut encoded = Vec::new();
        crate::exact_json::write_json_string_from_utf16(&mut encoded, &self.0);
        let source = String::from_utf8(encoded).map_err(serde::ser::Error::custom)?;
        let raw = RawValue::from_string(source).map_err(serde::ser::Error::custom)?;
        raw.serialize(serializer)
    }
}

impl<'de> Deserialize<'de> for JsonPayloadFragment {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        let raw = Box::<RawValue>::deserialize(deserializer)?;
        let scanner = crate::response_json::ResponseJsonScanner::parse(
            raw.get().as_bytes(),
            "JSON payload fragment is not a valid string",
        )
        .map_err(serde::de::Error::custom)?;
        if scanner.kind_at("") != Some(crate::response_json::FlatJsonKind::String) {
            return Err(serde::de::Error::custom(
                "JSON payload fragment must be a string",
            ));
        }
        let code_units = scanner
            .root_node()
            .string_units()
            .ok_or_else(|| serde::de::Error::custom("JSON payload fragment is not a string"))?;
        Ok(Self(code_units))
    }
}

impl From<&str> for JsonPayloadFragment {
    fn from(source: &str) -> Self {
        Self::from_text(source)
    }
}

impl From<String> for JsonPayloadFragment {
    fn from(source: String) -> Self {
        Self(source.encode_utf16().collect())
    }
}

fn json_source_from_utf16_units(code_units: &[u16]) -> String {
    let mut source = String::with_capacity(code_units.len());
    let mut index = 0;
    let mut in_string = false;
    let mut escaped = false;
    while index < code_units.len() {
        let unit = code_units[index];
        if in_string && escaped {
            if (0xD800..=0xDFFF).contains(&unit) {
                // Keep an invalid escaped surrogate invalid. Replacing it with a
                // JSON escape here could repair malformed source into valid JSON.
                source.push('\u{FFFD}');
            } else {
                source.push(char::from_u32(u32::from(unit)).expect("non-surrogate UTF-16 unit"));
            }
            escaped = false;
            index += 1;
        } else if in_string && unit == b'\\' as u16 {
            source.push('\\');
            escaped = true;
            index += 1;
        } else if unit == b'"' as u16 {
            source.push('"');
            in_string = !in_string;
            index += 1;
        } else if in_string
            && (0xD800..=0xDBFF).contains(&unit)
            && code_units
                .get(index + 1)
                .is_some_and(|next| (0xDC00..=0xDFFF).contains(next))
        {
            let low = code_units[index + 1];
            let scalar = 0x1_0000 + ((u32::from(unit) - 0xD800) << 10) + (u32::from(low) - 0xDC00);
            source.push(char::from_u32(scalar).expect("valid UTF-16 pair is a scalar"));
            index += 2;
        } else if in_string && (0xD800..=0xDFFF).contains(&unit) {
            use fmt::Write;
            write!(source, "\\u{unit:04x}").expect("String writes cannot fail");
            index += 1;
        } else if !in_string && (0xD800..=0xDFFF).contains(&unit) {
            // An unpaired surrogate outside a JSON string is not valid JSON.
            source.push('\u{FFFD}');
            index += 1;
        } else {
            source.push(
                char::from_u32(u32::from(unit)).expect("non-surrogate UTF-16 unit is a scalar"),
            );
            index += 1;
        }
    }
    source
}

